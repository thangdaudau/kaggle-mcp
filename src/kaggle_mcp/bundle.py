"""Pack a local project into a single Kaggle script kernel.

Kaggle script kernels accept exactly one source file, so the project code is
zipped, base64-embedded into a generated bootstrap script, and unpacked to
/tmp/kjob_code on the Kaggle machine. The job runs with cwd=/kaggle/working,
the directory Kaggle keeps as the run's output.
"""

from __future__ import annotations

import base64
import io
import json
import os
import re
import zipfile
from pathlib import Path

MAX_BUNDLE_BYTES = 2_000_000
EXCLUDED_DIRS = frozenset(
    {
        ".git", ".venv", "venv", "env", "__pycache__", "node_modules", ".ipynb_checkpoints",
        ".mypy_cache", ".pytest_cache", ".ruff_cache", ".claude", "kaggle_out",
    }
)  # fmt: skip
EXCLUDED_SUFFIXES = (".pyc", ".pyo")
SCRIPT_NAME = "kjob_main.py"


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def build_code_zip(project_dir: Path, exclude: Path | None = None) -> bytes:
    """Zip project_dir, skipping caches, virtualenvs and the `exclude` directory (the data dir)."""
    project_dir = project_dir.resolve()
    exclude = exclude.resolve() if exclude else None
    buf = io.BytesIO()
    sizes: list[tuple[int, str]] = []
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for root, dirs, files in os.walk(project_dir):
            root_path = Path(root)
            dirs[:] = sorted(
                d for d in dirs if d not in EXCLUDED_DIRS and (root_path / d).resolve() != exclude
            )
            for name in sorted(files):
                if name.endswith(EXCLUDED_SUFFIXES):
                    continue
                path = root_path / name
                rel = path.relative_to(project_dir).as_posix()
                zf.write(path, rel)
                sizes.append((path.stat().st_size, rel))
    data = buf.getvalue()
    if len(data) > MAX_BUNDLE_BYTES:
        biggest = ", ".join(f"{rel} ({size // 1024} KB)" for size, rel in sorted(sizes)[-5:])
        raise ValueError(
            f"code bundle is {len(data) // 1024} KB compressed "
            f"(limit {MAX_BUNDLE_BYTES // 1024} KB). "
            f"Move large files into data_dir. Largest files: {biggest}"
        )
    return data


def render_bootstrap(code_zip: bytes, entry: str, data_slug: str | None) -> str:
    payload = base64.b64encode(code_zip).decode("ascii")
    return _BOOTSTRAP.format(entry=entry, data_slug=data_slug, payload=payload)


def write_kernel_folder(
    folder: Path,
    *,
    kernel_ref: str,
    script: str,
    gpu: bool,
    internet: bool,
    dataset_sources: list[str],
) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    (folder / SCRIPT_NAME).write_text(script, encoding="utf-8")
    metadata = {
        "id": kernel_ref,
        "title": kernel_ref.split("/", 1)[1],
        "code_file": SCRIPT_NAME,
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": gpu,
        "enable_internet": internet,
        "dataset_sources": dataset_sources,
        "competition_sources": [],
        "kernel_sources": [],
    }
    (folder / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")


_BOOTSTRAP = """\
# Generated by kaggle-mcp. Runs the bundled project on Kaggle.
import base64, io, os, runpy, subprocess, sys, zipfile
from pathlib import Path

ENTRY = {entry!r}
DATA_SLUG = {data_slug!r}
PAYLOAD = "{payload}"

code_dir = Path("/tmp/kjob_code")
code_dir.mkdir(parents=True, exist_ok=True)
zipfile.ZipFile(io.BytesIO(base64.b64decode(PAYLOAD))).extractall(code_dir)
os.environ["KJOB_CODE_DIR"] = str(code_dir)

req = code_dir / "requirements.txt"
if req.exists():
    print("[kjob] pip install -r requirements.txt", flush=True)
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "-r", str(req)], check=True)


INPUT = Path("/kaggle/input")


def depth(root):
    return len(Path(root).relative_to(INPUT).parts)


def find_mount(slug):
    for root, dirs, _files in os.walk(INPUT):
        if Path(root).name == slug:
            return Path(root)
        if depth(root) >= 4:
            dirs[:] = []
    return None


if DATA_SLUG:
    mount = find_mount(DATA_SLUG)
    if mount is None:
        print("[kjob] /kaggle/input contents:", flush=True)
        for root, dirs, files in os.walk(INPUT):
            print(" ", root, dirs[:10], files[:10], flush=True)
            if depth(root) >= 3:
                dirs[:] = []
        raise SystemExit(f"[kjob] data dataset {{DATA_SLUG}} not mounted")
    os.environ["KJOB_DATA_DIR"] = str(mount)
    print(f"[kjob] KJOB_DATA_DIR={{mount}}", flush=True)

entry = code_dir / ENTRY
os.chdir("/kaggle/working")
sys.path[:0] = [str(entry.parent), str(code_dir)]
sys.argv = [str(entry)]
print(f"[kjob] running {{ENTRY}}", flush=True)
runpy.run_path(str(entry), run_name="__main__")
"""
